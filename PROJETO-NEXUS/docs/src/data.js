export const HEROES = roster.map((r, index) => {
  const [
    id,
    name,
    classId,
    title,
    basicName,
    skillName,
    ultimateName,
    hp,
    attack,
    defense,
    speed,
    weapon,
    animation,
    kind,
    power,
    effect,
    lore,
  ] = r;
  const healing = ["heal", "healAll"].includes(kind),
    protecting = ["shield", "shieldAll"].includes(kind);
  return {
    id,
    index,
    name,
    classId,
    title,
    lore,
    hp,
    attack,
    defense,
    speed,
    weapon,
    animation,
    role: healing
      ? "Suporte"
      : protecting
        ? "Guardião"
        : kind === "aoe"
          ? "Controlador"
          : "Atacante",
    basic: {
      id: "basic",
      name: basicName,
      kind: "damage",
      power: 1,
      cost: 0,
      cooldown: 0,
      description: "Causa dano a um rival e recupera 24 de energia.",
    },
    skill: {
      id: "skill",
      name: skillName,
      kind,
      power,
      effect,
      cost: 30,
      cooldown: 2,
      description: skillDescription(kind, effect, power),
    },
    ultimate: {
      id: "ultimate",
      name: ultimateName,
      kind: healing ? "healAll" : protecting ? "shieldAll" : "aoe",
      power: healing ? 0.42 : protecting ? 0.36 : 2.05,
      effect: healing ? "cleanse" : protecting ? "regen" : effect,
      cost: 80,
      cooldown: 0,
      description: healing
        ? "Recupera 42% da vida máxima de toda a equipe e purifica efeitos negativos."
        : protecting
          ? "Concede barreira de 36% da vida máxima e regeneração a toda a equipe."
          : "Atinge todos os rivais com 205% do poder de ataque e aplica o efeito da técnica.",
    },
  };
});
function skillDescription(kind, effect, power) {
  const statuses = {
    burn: "Aplica queimadura por 2 turnos.",
    weaken: "Reduz o ataque do alvo em 20% por 2 turnos.",
    expose: "Reduz a defesa do alvo em 25% por 2 turnos.",
    regen: "Concede regeneração por 2 turnos.",
    cleanse: "Remove efeitos negativos.",
  };
  return (
    {
      damage: `Causa ${Math.round(power * 100)}% do ataque a um rival.`,
      aoe: `Causa ${Math.round(power * 100)}% do ataque a todos os rivais.`,
      heal: `Recupera ${Math.round(power * 100)}% da vida máxima de um aliado.`,
      healAll: `Recupera ${Math.round(power * 100)}% da vida máxima da equipe.`,
      shield: `Protege um aliado com barreira de ${Math.round(power * 100)}% da vida máxima.`,
      shieldAll: `Protege a equipe com barreira de ${Math.round(power * 100)}% da vida máxima.`,
    }[kind] +
    " " +
    statuses[effect]
  );
}
