export const CARDS: readonly Card[] = THEME_IDS.flatMap((theme) =>
  names[theme].map((name, position) => ({
    id: `${theme}-${position}`,
    name,
    theme,
    position,
  })),
);
export const CARD_BY_ID = new Map(CARDS.map((card) => [card.id, card]));
export function getCard(id: string): Card {
  const card = CARD_BY_ID.get(id);
  if (!card) throw new Error('Carta desconhecida.');
  return card;
}
export function pool(themes: readonly ThemeId[]): Card[] {
  return CARDS.filter((card) => themes.includes(card.theme));
}
